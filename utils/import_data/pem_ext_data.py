def import_rows(museum_key="pem"):
    """
    转成 import_artworks.read_museum 的行格式，在 Excel 那 196 行之后追加。

    · name_key 取英文题名 —— PEM 是英文源馆，与现有 196 行同规矩；
      中文一律留 None，由 translate_artwork.py 补并落进 translations_*.csv。
    · gallery 已经是 26 个实体展厅里的名字（由证据定出），所以带
      gallery_resolved=True，**跳过 LABEL_MAP 那一步** —— 那是给旧主题标签用的。
    · on_view 只有两态来源：馆方页面写了在展就是「在展」，没写就是「未知」。
      **没写不等于不在展**，不要把 None 读成「未在展」。
    · tier 一律 None：这批还没评级，导出时应当显示为「无评级」而不是任何一档。
    """
    rows = []
    for r in ITEMS:
        rows.append(dict(
            museum_key=museum_key, source_seq=r["seq"],
            name_key=r["title"], name_zh=None, name_en=r["title"],
            gallery=r["gallery"], gallery_resolved=True,
            desc_zh=None, desc_en=r["desc"],
            medium=r["material"], tier=None, reason=None,
            irreplaceability=None,
            on_view=("在展" if r["onview_raw"] else "未知"),
            has_image=bool(r["image"]), image_url=r["image"],
            official_url=r["url"],
        ))
    return rows


def tier_rows():
    """
    转成 tier_v3.load_items 的行格式。**与 import_rows 同出一处** ——
    tier_v3 直接读 Excel，漏了这里它就永远看不到新行（「两条腿必须一致」）。

    category 取官网栏目名：源 Excel 那一列叫「Category / 类别」，
    对新行而言最诚实的对应物就是馆方自己把它归在哪个栏目。Wikidata 行没有栏目，留空。
    """
    out = []
    for r in ITEMS:
        sec = r["section"] or ""
        out.append({
            "seq": r["seq"], "name_en": r["title"], "name_cn": "",
            "gallery": r["gallery"] or "",
            "description": r["desc"] or "",
            "category": sec.replace("-", " ").title() if sec else "",
            "tier_old": "",
        })
    return out


def _check():
    seqs = [r["seq"] for r in ITEMS]
    assert len(set(seqs)) == len(seqs), "seq 有重复"
    assert not seqs or min(seqs) > EXCEL_ROWS, "seq 撞上了现有展品"
    assert seqs == sorted(seqs), "seq 未按升序排列"
    # 断号是允许的：号一旦发出去就不收回。为了连续而重新编号，
    # 会让它之后的每一件展品换号 —— 那正是 seq 稳定性要防的事。
    ids = [r["identity"] for r in ITEMS]
    assert len(set(ids)) == len(ids), "身份键有重复"


